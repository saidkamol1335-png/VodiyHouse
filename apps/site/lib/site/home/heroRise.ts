// Колоннада рендеров первого экрана главной: пять прямоугольных рамок, центральная шире. До правок
// 15.11 (п. 1) рамки прятались за горизонтом и выходили прокруткой («Ufq · Раскол»); теперь стоят над
// горизонтом сразу, во всех режимах, — здесь осталось только их описание.

export type HeroSlot = "c" | "l1" | "r1" | "l2" | "r2";

export type HeroTower = {
  slot: HeroSlot;
  /** Индекс в HERO_RENDERS. */
  render: number;
  /** 0 — центр, 1 — ближние, 2 — крайние (только на широком экране). */
  rank: 0 | 1 | 2;
  /** −1 — слева, 1 — справа, 0 — центр. */
  side: -1 | 0 | 1;
  /** Доля высоты кадра, которую показываем: ниже — то, что прячем (горка, вывеска). */
  safeShare: number;
};

